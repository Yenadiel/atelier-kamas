import * as ResEdit from 'resedit';
import * as PE from 'pe-library';
import fs from 'fs';
const exePath=process.argv[2], icoPath=process.argv[3];
const exe=PE.NtExecutable.from(fs.readFileSync(exePath),{ignoreCert:true});
const res=PE.NtExecutableResource.from(exe);
const ico=ResEdit.Data.IconFile.from(fs.readFileSync(icoPath));
ResEdit.Resource.IconGroupEntry.replaceIconsForResource(res.entries,1,1033,ico.icons.map(i=>i.data));
const vi=ResEdit.Resource.VersionInfo.fromEntries(res.entries)[0];
vi.setStringValues({lang:1033,codepage:1200},{ProductName:'Atelier Kamas',FileDescription:'Atelier Kamas',CompanyName:'Atelier Kamas',OriginalFilename:'Atelier Kamas.exe',InternalName:'Atelier Kamas',LegalCopyright:''});
vi.setFileVersion(1,0,0,0,1033);vi.setProductVersion(1,0,0,0,1033);
vi.outputToResourceEntries(res.entries);
res.outputResource(exe);
fs.writeFileSync(exePath,Buffer.from(exe.generate()));
console.log('ok');
